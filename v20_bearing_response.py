"""V20 linearized bearing-coefficient and synchronous-unbalance response tools.

This module augments the V19 Timoshenko rotor matrices. Bearing coefficients are
user-supplied linearized coefficients (not generated by a Reynolds-equation
fluid-film solver). The unbalance response is a steady-state harmonic solution.
"""
from __future__ import annotations
import numpy as np
import pandas as pd
from scipy.linalg import eigvals


def _finite(name, value):
    value = float(value)
    if not np.isfinite(value):
        raise ValueError(f"{name} must be finite")
    return value


def apply_linearized_bearing_coefficients(rotor, coefficients, support_nodes=None):
    """Return copied rotor matrices with anisotropic/cross-coupled bearing K,C.

    coefficients keys: kxx, kyy, kxy, kyx [N/m], cxx, cyy, cxy, cyx [N s/m].
    Positive cross-coupled terms are accepted; stability must be assessed.
    """
    required = ("kxx", "kyy", "kxy", "kyx", "cxx", "cyy", "cxy", "cyx")
    missing = [key for key in required if key not in coefficients]
    if missing:
        raise ValueError(f"Missing bearing coefficients: {', '.join(missing)}")
    vals = {key: _finite(key, coefficients[key]) for key in required}
    if vals["kxx"] <= 0 or vals["kyy"] <= 0:
        raise ValueError("Direct bearing stiffness kxx and kyy must be > 0")
    if vals["cxx"] < 0 or vals["cyy"] < 0:
        raise ValueError("Direct bearing damping cxx and cyy must be >= 0")
    nnode = len(rotor["nodes_m"])
    if support_nodes is None:
        support_nodes = (0, nnode - 1)
    nodes = tuple(int(node) for node in support_nodes)
    if not nodes or any(node < 0 or node >= nnode for node in nodes):
        raise ValueError("support_nodes must contain valid node indices")
    out = {key: (value.copy() if isinstance(value, np.ndarray) else value)
           for key, value in rotor.items()}
    Kb = np.zeros_like(out["K"]); Cb = np.zeros_like(out["C"])
    kb = np.array([[vals["kxx"], vals["kxy"]], [vals["kyx"], vals["kyy"]]])
    cb = np.array([[vals["cxx"], vals["cxy"]], [vals["cyx"], vals["cyy"]]])
    for node in nodes:
        dofs = [4 * node, 4 * node + 2]
        Kb[np.ix_(dofs, dofs)] += kb
        Cb[np.ix_(dofs, dofs)] += cb
    # Remove the isotropic end-support terms assembled by V19 before replacement.
    base_k = float(rotor.get("bearing_stiffness_n_m", 0.0))
    base_c = float(rotor.get("bearing_damping_n_s_m", 0.0))
    for node in (0, nnode - 1):
        for dof in (4 * node, 4 * node + 2):
            out["K"][dof, dof] -= base_k
            out["C"][dof, dof] -= base_c
    out["K"] += Kb; out["C"] += Cb
    out["bearing_coefficients"] = vals
    out["bearing_support_nodes"] = nodes
    return out


def synchronous_unbalance_response(rotor, rpm_values, unbalance_kg_m=1e-4,
                                    phase_deg=0.0, force_node=None):
    """Calculate linear steady-state 1X response to a rotating mass eccentricity.

    Force amplitude is U*Omega**2, where U=m*e (kg m). Returns displacement
    amplitudes at the disk node (or requested force node), plus response phase.
    """
    rpm = np.asarray(rpm_values, dtype=float)
    if rpm.ndim != 1 or len(rpm) < 2 or np.any(~np.isfinite(rpm)) or np.any(rpm <= 0):
        raise ValueError("rpm_values must be a finite positive 1D array with >=2 values")
    U = _finite("unbalance_kg_m", unbalance_kg_m)
    phase = np.deg2rad(_finite("phase_deg", phase_deg))
    if U < 0:
        raise ValueError("unbalance_kg_m must be >= 0")
    node = rotor["disk_node"] if force_node is None else int(force_node)
    if node < 0 or node >= len(rotor["nodes_m"]):
        raise ValueError("force_node is outside the rotor mesh")
    M, C, K, G = (rotor[key] for key in ("M", "C", "K", "G"))
    ix, iy = 4 * node, 4 * node + 2
    rows = []
    for speed in rpm:
        omega = speed * 2 * np.pi / 60
        F = np.zeros(K.shape[0], dtype=complex)
        famp = U * omega**2
        F[ix] = famp * np.cos(phase) - 1j * famp * np.sin(phase)
        F[iy] = famp * np.sin(phase) + 1j * famp * np.cos(phase)
        Z = K - omega**2 * M + 1j * omega * (C + omega * G)
        try:
            q = np.linalg.solve(Z, F)
        except np.linalg.LinAlgError:
            q = np.linalg.lstsq(Z, F, rcond=None)[0]
        rows.append({"rpm": float(speed), "frequency_hz": float(speed / 60),
                     "force_amplitude_n": float(famp),
                     "x_amplitude_m": float(abs(q[ix])),
                     "y_amplitude_m": float(abs(q[iy])),
                     "resultant_amplitude_m": float(np.hypot(abs(q[ix]), abs(q[iy]))),
                     "x_phase_deg": float(np.rad2deg(np.angle(q[ix]))),
                     "y_phase_deg": float(np.rad2deg(np.angle(q[iy])))})
    return pd.DataFrame(rows)


def stability_sweep(rotor, rpm_values):
    """Return rightmost eigenvalue and modal damping indicators vs spin speed.

    A positive maximum real part indicates linear instability in this model.
    Log decrement is reported for the least-damped oscillatory eigenvalue only.
    """
    rpm = np.asarray(rpm_values, dtype=float)
    if rpm.ndim != 1 or len(rpm) < 2 or np.any(~np.isfinite(rpm)) or np.any(rpm < 0):
        raise ValueError("rpm_values must be a finite non-negative 1D array with >=2 values")
    M, C, K, G = (rotor[key] for key in ("M", "C", "K", "G"))
    n = K.shape[0]
    MinvK = np.linalg.solve(M, K); MinvC = np.linalg.solve(M, C); MinvG = np.linalg.solve(M, G)
    Z = np.zeros((n, n)); I = np.eye(n); rows = []
    for speed in rpm:
        omega = speed * 2 * np.pi / 60
        A = np.block([[Z, I], [-MinvK, -(MinvC + omega * MinvG)]])
        lam = eigvals(A, check_finite=False)
        right = lam[int(np.argmax(np.real(lam)))]
        oscillatory = lam[np.imag(lam) > 1e-8]
        least = oscillatory[int(np.argmax(np.real(oscillatory)))] if len(oscillatory) else right
        wn = abs(least)
        zeta = float(-np.real(least) / wn) if wn else np.nan
        wd = abs(np.imag(least))
        logdec = float(2 * np.pi * (-np.real(least)) / wd) if wd > 1e-12 else np.nan
        rows.append({"rpm": float(speed), "max_real_eigenvalue_per_s": float(np.max(np.real(lam))),
                     "least_damped_frequency_hz": float(wd / (2 * np.pi)),
                     "least_damped_zeta": zeta, "log_decrement": logdec,
                     "stability": "Unstable" if np.max(np.real(lam)) > 1e-7 else "Stable/neutral"})
    return pd.DataFrame(rows)
